constexpr Color Rgb(std::uint8_t r, std::uint8_t g, std::uint8_t b,
                    std::uint8_t a = 255) {
    return Color{r, g, b, a};
}

// PS5-adjacent palette from the reference app: deep violet surfaces, lavender
// ink and the B072FF/FF6BD6 accent pair. The new layout keeps its own spacing
// and typography; only the visual identity is shared.
