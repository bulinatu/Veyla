#include "ui/theme.h"

namespace brp::next {
namespace {

constexpr Color Rgb(std::uint8_t r, std::uint8_t g, std::uint8_t b,
                    std::uint8_t a = 255) {
    return Color{r, g, b, a};
}

const ThemeTokens kDark{
    Rgb(0x0B, 0x0C, 0x0E),  // background
    Rgb(0x14, 0x16, 0x1A),  // surface
    Rgb(0x1B, 0x1E, 0x24),  // surface_alt
    Rgb(0x22, 0x26, 0x2E),  // surface_hover
    Rgb(0x2A, 0x2F, 0x38),  // border
    Rgb(0x3A, 0x41, 0x4D),  // border_strong
    Rgb(0xF2, 0xF4, 0xF7),  // text
    Rgb(0xA7, 0xAF, 0xBD),  // text_dim
    Rgb(0x6C, 0x76, 0x86),  // text_faint
    Rgb(0x76, 0xB9, 0x00),  // accent
    Rgb(0x8F, 0xD4, 0x00),  // accent_hover
    Rgb(0x0B, 0x0C, 0x0E),  // accent_text
    Rgb(0x4A, 0xDE, 0x80),  // success
    Rgb(0xFB, 0xBF, 0x24),  // warning
    Rgb(0xF8, 0x71, 0x71),  // error
};

const ThemeTokens kLight{
    Rgb(0xF4, 0xF6, 0xF8),
    Rgb(0xFF, 0xFF, 0xFF),
    Rgb(0xED, 0xF0, 0xF4),
    Rgb(0xE3, 0xE8, 0xEF),
    Rgb(0xD5, 0xDB, 0xE4),
    Rgb(0xB7, 0xC0, 0xCC),
    Rgb(0x14, 0x17, 0x1C),
    Rgb(0x4B, 0x55, 0x63),
    Rgb(0x7B, 0x84, 0x94),
    Rgb(0x5A, 0x8F, 0x00),
    Rgb(0x6F, 0xA8, 0x00),
    Rgb(0xFF, 0xFF, 0xFF),
    Rgb(0x15, 0x80, 0x3D),
    Rgb(0xB4, 0x53, 0x09),
    Rgb(0xB9, 0x1C, 0x1C),
};

}  // namespace

const ThemeTokens& ThemeFor(Theme theme) {
    return theme == Theme::Light ? kLight : kDark;
}

}  // namespace brp::next
